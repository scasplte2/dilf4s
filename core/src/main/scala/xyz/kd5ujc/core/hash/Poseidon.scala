package xyz.kd5ujc.core.hash

import cats.{Eq, Show}

import scala.annotation.tailrec

sealed trait PoseidonError extends Product with Serializable

object PoseidonError {
  final case class InputCount(count: Int, max: Int) extends PoseidonError
  // a caller's value can be any size: it is shown by its bit length, never its digits
  final case class NonCanonical(value: BigInt) extends PoseidonError {
    override def toString: String = s"NonCanonical(a ${value.bitLength}-bit value)"
  }
}

/**
 * An element of the BN254 scalar field, `0 <= value < r`, valid by construction: values enter only through
 * [[Fr.from]] (checked) or [[Fr.reduce]] (mod r), so everything typed `Fr` downstream (Poseidon inputs and outputs,
 * Merkle leaves, siblings, roots) needs no further range checks. Opaque: its `BigInt` is visible only inside [[Fr]].
 */
opaque type Fr = BigInt

object Fr {

  /** The BN254 scalar field modulus `r`. */
  val Modulus: BigInt = BigInt("21888242871839275222246405745257275088548364400416034343698204186575808495617")

  val Zero: Fr = BigInt(0)

  def from(value: BigInt): Either[PoseidonError, Fr] =
    Either.cond(value >= 0 && value < Modulus, value, PoseidonError.NonCanonical(value))

  def reduce(value: BigInt): Fr = value.mod(Modulus)

  extension (f: Fr) def value: BigInt = f

  given Eq[Fr] = Eq.fromUniversalEquals
  given Show[Fr] = Show.show(_.toString)
}

/**
 * One width's constants in the optimised form (the Poseidon paper's Appendix B, laid out as circomlibjs's
 * `poseidon_opt`), generated by `PoseidonConstantsGen` from the paper's base constants. With `h = RF / 2` and
 * `RP = partialRounds`:
 *
 *   - `constants`, `8t + RP` elements: `t` added before the first S-box; `t` after each of the first `h` full rounds'
 *     S-boxes; one per partial round, added to element 0 after its S-box; and `t` after each of the last `h` full
 *     rounds' S-boxes but the final one, which adds none.
 *   - `mds`, the MDS matrix `M`, for every full round but the `h`-th, which uses `preSparse`.
 *   - `sparse`, `2t - 1` elements per partial round: a first row `w` (`t`) and the rest of the first column `v`
 *     (`t - 1`); the rest of the matrix is the identity.
 *
 * Matrices act as `new_i = Σ_j m_ij · s_j`.
 */
final private[hash] case class PoseidonParams(
  t:             Int,
  partialRounds: Int,
  constants:     Vector[BigInt],
  sparse:        Vector[BigInt],
  mds:           Vector[Vector[BigInt]],
  preSparse:     Vector[Vector[BigInt]]
)

/**
 * Poseidon over the BN254 scalar field, byte-compatible with circomlib / circomlibjs (`poseidon([...])`): x^5 S-box,
 * 8 full rounds, width `t = inputs + 1`, state `[0, in_0, ..]`, output `state[0]`. Widths 2..5 (1..4 inputs): the
 * fixed-arity functions are total; [[hash]] checks only the input count.
 *
 * Evaluated in the optimised form of [[PoseidonParams]], in Montgomery arithmetic over four 64-bit limbs. Tests check
 * it against the permutation as defined, over the base constants.
 *
 * **Public data only**: the arithmetic is variable time. Never hash secrets (note values, nullifier keys) here.
 */
object Poseidon {

  val MaxInputs: Int = 4

  def hash1(a: Fr): Fr = permute(W2, Vector(a))
  def hash2(a: Fr, b: Fr): Fr = permute(W3, Vector(a, b))
  def hash3(a: Fr, b: Fr, c: Fr): Fr = permute(W4, Vector(a, b, c))
  def hash4(a: Fr, b: Fr, c: Fr, d: Fr): Fr = permute(W5, Vector(a, b, c, d))

  /** Two-to-one compression for Merkle nodes: `poseidon([l, r])`. */
  def compress(l: Fr, r: Fr): Fr = hash2(l, r)

  def hash(inputs: Seq[Fr]): Either[PoseidonError, Fr] =
    byWidth
      .get(inputs.size + 1)
      .toRight(PoseidonError.InputCount(inputs.size, MaxInputs))
      .map(m => permute(m, inputs.toVector))

  /** A width's constants in Montgomery form, converted once. */
  final private case class Mont(
    t:             Int,
    partialRounds: Int,
    constants:     Vector[FrMont],
    sparse:        Vector[FrMont],
    mds:           Vector[Vector[FrMont]],
    preSparse:     Vector[Vector[FrMont]]
  )

  private def montgomery(p: PoseidonParams): Mont =
    Mont(
      p.t,
      p.partialRounds,
      p.constants.map(FrMont(_)),
      p.sparse.map(FrMont(_)),
      p.mds.map(_.map(FrMont(_))),
      p.preSparse.map(_.map(FrMont(_)))
    )

  private val W2 = montgomery(PoseidonConstants.Width2)
  private val W3 = montgomery(PoseidonConstants.Width3)
  private val W4 = montgomery(PoseidonConstants.Width4)
  private val W5 = montgomery(PoseidonConstants.Width5)
  private val byWidth: Map[Int, Mont] = Map(2 -> W2, 3 -> W3, 4 -> W4, 5 -> W5)

  private val Half: Int = PoseidonConstants.FullRounds / 2

  private def pow5(a: FrMont): FrMont = {
    val a2 = a * a
    a2 * a2 * a
  }

  private def dot(row: Vector[FrMont], s: Vector[FrMont]): FrMont =
    row.indices.foldLeft(FrMont.Zero)((acc, j) => acc + row(j) * s(j))

  /** S-box every element, add the constants from `at`, and multiply by `m`. */
  private def fullRound(f: Mont, m: Vector[Vector[FrMont]], s: Vector[FrMont], at: Int): Vector[FrMont] = {
    val boxed = Vector.tabulate(f.t)(i => pow5(s(i)) + f.constants(at + i))
    m.map(dot(_, boxed))
  }

  /** The permutation of `[0, inputs..]`, whose width selects `f`. */
  private def permute(f: Mont, inputs: Vector[Fr]): Fr = {
    val t = f.t
    val first = Vector.tabulate(t)(i => (if (i == 0) FrMont.Zero else FrMont(inputs(i - 1).value)) + f.constants(i))
    @tailrec def full(r: Int, until: Int, s: Vector[FrMont], at: Int => Int): Vector[FrMont] =
      if (r >= until) s else full(r + 1, until, fullRound(f, f.mds, s, at(r)), at)
    @tailrec def partial(r: Int, s: Vector[FrMont]): Vector[FrMont] =
      if (r >= f.partialRounds) s
      else {
        val x0 = pow5(s(0)) + f.constants((Half + 1) * t + r)
        val at = (2 * t - 1) * r
        val s0 = (1 until t).foldLeft(x0 * f.sparse(at))((acc, j) => acc + s(j) * f.sparse(at + j))
        partial(r + 1, Vector.tabulate(t)(k => if (k == 0) s0 else s(k) + x0 * f.sparse(at + t + k - 1)))
      }
    val opened = fullRound(f, f.preSparse, full(1, Half, first, r => r * t), Half * t)
    val tail = (Half + 1) * t + f.partialRounds
    val closing = full(0, Half - 1, partial(0, opened), r => tail + r * t)
    // the last round adds no constant, and only element 0 of its output is read
    val boxed = closing.map(pow5)
    Fr.reduce(f.mds.headOption.fold(FrMont.Zero)(dot(_, boxed)).toBigInt)
  }
}
