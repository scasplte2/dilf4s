package xyz.kd5ujc.core.hash

import java.nio.charset.StandardCharsets.UTF_8
import java.nio.file.{Files, Path, Paths}

import cats.effect.{ExitCode, IO, IOApp}
import cats.syntax.all._

import io.circe.{ACursor, Json}

/**
 * Writes `PoseidonConstants.scala` from [[PoseidonDerivation]]. Run from the repository root:
 * `sbt "core/Test/runMain xyz.kd5ujc.core.hash.PoseidonConstantsGen"`.
 */
object PoseidonConstantsGen extends IOApp {

  val path: Path = Paths.get("core", "src", "main", "scala", "xyz", "kd5ujc", "core", "hash", "PoseidonConstants.scala")

  val widths: List[Int] = List(2, 3, 4, 5)

  def derived(t: Int): Either[String, (PoseidonDerivation.Base, PoseidonParams)] =
    PoseidonDerivation.base(t).flatMap(b => PoseidonDerivation.optimize(b).tupleLeft(b))

  private def vector(xs: Vector[BigInt], indent: String): String =
    xs.map(x => s"""$indent  BigInt("$x")""").mkString(s"Vector(\n", ",\n", s"\n$indent)")

  private def matrix(m: Vector[Vector[BigInt]], indent: String): String =
    m.map(row => s"$indent  " + vector(row, indent + "  ")).mkString("Vector(\n", ",\n", s"\n$indent)")

  private def width(p: PoseidonParams): String =
    s"""private object PoseidonWidth${p.t} {
       |  val params: PoseidonParams = PoseidonParams(
       |    t = ${p.t},
       |    partialRounds = ${p.partialRounds},
       |    constants = ${vector(p.constants, "    ")},
       |    sparse = ${vector(p.sparse, "    ")},
       |    mds = ${matrix(p.mds, "    ")},
       |    preSparse = ${matrix(p.preSparse, "    ")}
       |  )
       |}
       |""".stripMargin

  def source(params: List[PoseidonParams]): String =
    s"""package xyz.kd5ujc.core.hash
       |
       |// GENERATED by PoseidonConstantsGen (core/src/test). DO NOT EDIT. Regenerate from the repository root with
       |//   sbt "core/Test/runMain xyz.kd5ujc.core.hash.PoseidonConstantsGen"
       |//
       |// Poseidon over BN254 in the optimised form of PoseidonParams, derived from the base constants that the Poseidon
       |// paper's Grain LFSR generates (eprint 2019/458): see PoseidonDerivation and docs/specs/zk.md section 3.
       |// PoseidonSuite checks that this file is the derivation's output.
       |
       |private[hash] object PoseidonConstants {
       |  val FullRounds: Int = ${PoseidonDerivation.FullRounds}
       |${params.map(p => s"  val Width${p.t}: PoseidonParams = PoseidonWidth${p.t}.params").mkString("\n")}
       |}
       |
       |${params.map(width).mkString("\n")}""".stripMargin

  def run(args: List[String]): IO[ExitCode] =
    widths
      .traverse(t => derived(t).map(_._2))
      .leftMap(new IllegalStateException(_))
      .liftTo[IO]
      .flatMap(ps => IO.blocking(Files.write(path, source(ps).getBytes(UTF_8))))
      .flatMap(p => IO.println(s"wrote $p"))
      .as(ExitCode.Success)
}

/**
 * Compares the derivation with circomlibjs: `sbt "core/Test/runMain xyz.kd5ujc.core.hash.PoseidonCircomlibCheck <dir>"`,
 * where `<dir>` holds circomlibjs's `src/poseidon_constants.js` and `src/poseidon_constants_opt.js`. Dev only:
 * circomlibjs is GPL-3.0, so its files stay out of the repository. Prints each table's verdict and each width's
 * [[PoseidonDerivation.digest]] over circomlibjs's tables, which `PoseidonSuite` pins.
 */
object PoseidonCircomlibCheck extends IOApp {

  private def load(dir: Path, name: String): IO[Json] =
    IO.blocking(new String(Files.readAllBytes(dir.resolve(name)), UTF_8)).flatMap { text =>
      // `export default { ... };`: the object is JSON
      io.circe.parser.parse(text.drop(text.indexOf('{')).trim.stripSuffix(";")).liftTo[IO]
    }

  private def numbers(c: ACursor): Either[String, Vector[BigInt]] =
    c.as[Vector[String]]
      .leftMap(_.getMessage)
      .flatMap(_.traverse(h => Either.catchNonFatal(BigInt(h.stripPrefix("0x"), 16)).leftMap(_.toString)))

  private def table(c: ACursor): Either[String, Vector[Vector[BigInt]]] =
    c.values.toRight("not an array").flatMap(_.toVector.traverse(j => numbers(j.hcursor)))

  final case class Circom(base: PoseidonDerivation.Base, opt: PoseidonParams)

  /** circomlibjs's tables for width `t`. Its optimised `M` and `P` are stored transposed (`new_i = Σ_j M_ji s_j`). */
  private def circom(base: Json, opt: Json, t: Int, rp: Int): Either[String, Circom] = {
    val k = t - 2
    def at(j: Json, key: String) = j.hcursor.downField(key).downN(k)
    (numbers(at(base, "C")), table(at(base, "M")), numbers(at(opt, "C")), numbers(at(opt, "S")), table(at(opt, "M")), table(at(opt, "P")))
      .mapN((bc, bm, c, s, m, p) => Circom(PoseidonDerivation.Base(t, rp, bc, bm), PoseidonParams(t, rp, c, s, m.transpose, p.transpose)))
  }

  def run(args: List[String]): IO[ExitCode] =
    args.headOption
      .map(Paths.get(_))
      .toRight(new IllegalArgumentException("usage: PoseidonCircomlibCheck <circomlibjs src dir>"))
      .liftTo[IO]
      .flatMap { dir =>
        (load(dir, "poseidon_constants.js"), load(dir, "poseidon_constants_opt.js")).flatMapN { (base, opt) =>
          PoseidonConstantsGen.widths.traverse { t =>
            PoseidonConstantsGen.derived(t).flatMap {
              case (b, o) =>
                circom(base, opt, t, b.partialRounds).map { c =>
                  val verdicts = List(
                    "base round constants" -> (c.base.roundConstants == b.roundConstants),
                    "base MDS"             -> (c.base.mds == b.mds),
                    "optimised constants"  -> (c.opt.constants == o.constants),
                    "sparse matrices"      -> (c.opt.sparse == o.sparse),
                    "optimised MDS"        -> (c.opt.mds == o.mds),
                    "pre-sparse matrix"    -> (c.opt.preSparse == o.preSparse)
                  )
                  (t, verdicts, PoseidonDerivation.digest(c.base, c.opt))
                }
            }
          }
            .leftMap(new IllegalStateException(_))
            .liftTo[IO]
            .flatMap { rows =>
              rows.traverse_ {
                case (t, verdicts, digest) =>
                  IO.println(s"t = $t: circomlibjs digest $digest") *>
                  verdicts.traverse_ { case (name, ok) => IO.println(s"  ${if (ok) "match   " else "MISMATCH"} $name") }
              }
                .as(if (rows.forall(_._2.forall(_._2))) ExitCode.Success else ExitCode.Error)
            }
        }
      }
}
