//! Groth16 over BN254 (docs/specs/zk.md §2), and SP1's Groth16 wrapper ([`sp1`]).
//!
//! A proof is 256 bytes, `A (G1) || B (G2) || C (G1)`; `A`, `B` and `C` must not be the identity, and each public
//! input must be below `r`. With `L = IC_0 + sum x_i IC_(i+1)`, the proof is accepted if and only if
//! `e(-A, B) e(alpha, beta) e(L, gamma) e(C, delta) = 1`. The checks run in the reference's order, so each refusal is
//! the same [`Groth16Error`] kind.

use alloc::string::String;
use alloc::vec::Vec;
use core::fmt;

use bn::{Fr, G1, G2, Group, Gt};

use super::{G1_BYTES, G2_BYTES, WORD_BYTES, ZkError, decode_g1, decode_g2};

/// A proof's width.
pub const PROOF_BYTES: usize = 256;

/// `r`, the order of G1 and G2, big-endian.
const R: [u8; WORD_BYTES] = [
    0x30, 0x64, 0x4e, 0x72, 0xe1, 0x31, 0xa0, 0x29, 0xb8, 0x50, 0x45, 0xb6, 0x81, 0x81, 0x58, 0x5d, 0x28, 0x33, 0xe8,
    0x48, 0x79, 0xb9, 0x70, 0x91, 0x43, 0xe1, 0xf5, 0x93, 0xf0, 0x00, 0x00, 0x01,
];

/// Why a proof was not accepted.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Groth16Error {
    /// Not a proof or input of the expected shape: lengths, non-canonical field elements, the number of inputs.
    Malformed {
        /// What was wrong.
        reason: String,
    },
    /// Well formed but invalid: a point off the curve, outside the subgroup or the identity, or an input not below `r`.
    InvalidProof {
        /// What was wrong.
        reason: String,
    },
    /// The pairing equation does not hold.
    PairingCheckFailed,
    /// A framing check of a wrapper (SP1's selector, exit code or VK root) failed.
    Rejected {
        /// What was wrong.
        reason: String,
    },
}

impl fmt::Display for Groth16Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Malformed { reason } => write!(f, "malformed: {reason}"),
            Self::InvalidProof { reason } => write!(f, "invalid proof: {reason}"),
            Self::PairingCheckFailed => f.write_str("the pairing check failed"),
            Self::Rejected { reason } => write!(f, "rejected: {reason}"),
        }
    }
}

impl From<ZkError> for Groth16Error {
    fn from(e: ZkError) -> Self {
        match e {
            ZkError::Malformed { reason } => Self::Malformed { reason },
            ZkError::InvalidPoint { reason } => Self::InvalidProof { reason },
        }
    }
}

fn malformed(reason: &str) -> Groth16Error {
    Groth16Error::Malformed { reason: reason.into() }
}

fn invalid(reason: &str) -> Groth16Error {
    Groth16Error::InvalidProof { reason: reason.into() }
}

/// A verifying key `(alpha, beta, gamma, delta, IC)`, its points checked when it is built.
#[derive(Clone, Debug)]
pub struct VerifyingKey {
    alpha: G1,
    beta: G2,
    gamma: G2,
    delta: G2,
    ic0: G1,
    ic: Vec<G1>,
}

impl VerifyingKey {
    /// A key from its encoded points; `ic` holds `IC_0` then one point per public input. Every point must be a
    /// valid, finite point: an identity in a key could cancel terms of the pairing equation, so that some proof would
    /// verify for every input.
    pub fn from_bytes(
        alpha: &[u8; G1_BYTES],
        beta: &[u8; G2_BYTES],
        gamma: &[u8; G2_BYTES],
        delta: &[u8; G2_BYTES],
        ic: &[[u8; G1_BYTES]],
    ) -> Result<Self, Groth16Error> {
        let (first, rest) = ic.split_first().ok_or_else(|| malformed("IC needs IC_0"))?;
        Ok(Self {
            alpha: finite_g1(alpha, "alpha")?,
            beta: finite_g2(beta, "beta")?,
            gamma: finite_g2(gamma, "gamma")?,
            delta: finite_g2(delta, "delta")?,
            ic0: finite_g1(first, "IC_0")?,
            ic: rest.iter().map(|p| finite_g1(p, "an IC point")).collect::<Result<_, _>>()?,
        })
    }

    /// The number of public inputs a proof under this key takes.
    pub fn public_inputs(&self) -> usize {
        self.ic.len()
    }
}

fn finite_g1(bytes: &[u8; G1_BYTES], role: &str) -> Result<G1, Groth16Error> {
    let p = decode_g1(bytes)?;
    if p.is_zero() { Err(malformed(&alloc::format!("the key's {role} is the identity"))) } else { Ok(p) }
}

fn finite_g2(bytes: &[u8; G2_BYTES], role: &str) -> Result<G2, Groth16Error> {
    let p = decode_g2(bytes)?;
    if p.is_zero() { Err(malformed(&alloc::format!("the key's {role} is the identity"))) } else { Ok(p) }
}

/// Whether `x`, 32 bytes big-endian, is below `r`.
fn in_fr(x: &[u8; WORD_BYTES]) -> bool {
    x < &R
}

/// Verifies `proof` for `inputs` (each 32 bytes big-endian, below `r`) under `vk`.
pub fn verify(vk: &VerifyingKey, proof: &[u8], inputs: &[[u8; WORD_BYTES]]) -> Result<(), Groth16Error> {
    let proof: &[u8; PROOF_BYTES] = proof
        .try_into()
        .map_err(|_| malformed(&alloc::format!("a proof is {PROOF_BYTES} bytes, got {}", proof.len())))?;
    let (a, rest) = proof.split_at(G1_BYTES);
    let (b, c) = rest.split_at(G2_BYTES);
    for (p, role) in [(a, "A"), (b, "B"), (c, "C")] {
        if p.iter().all(|x| *x == 0) {
            return Err(invalid(&alloc::format!("{role} is the identity")));
        }
    }
    // A's coordinates are read before the inputs are checked, as negating A needs them
    let a = decode_coordinates(a)?;
    if inputs.len() != vk.public_inputs() {
        return Err(malformed(&alloc::format!("expected {} public inputs, got {}", vk.public_inputs(), inputs.len())));
    }
    if !inputs.iter().all(in_fr) {
        return Err(invalid("a public input is not in Fr"));
    }
    let l = inputs.iter().zip(&vk.ic).try_fold(vk.ic0, |acc, (x, p)| {
        Fr::from_slice(x).map(|s| acc + *p * s).map_err(|_| invalid("a public input is not in Fr"))
    })?;
    let neg_a = decode_g1(&a)?;
    let (b, c) = (decode_g2(b)?, decode_g1(c)?);
    let pairs: Vec<(G1, G2)> = [(neg_a, b), (vk.alpha, vk.beta), (l, vk.gamma), (c, vk.delta)]
        .into_iter()
        .filter(|(p, q)| !p.is_zero() && !q.is_zero())
        .collect();
    if pairs.is_empty() || bn::pairing_batch(&pairs) == Gt::one() {
        Ok(())
    } else {
        Err(Groth16Error::PairingCheckFailed)
    }
}

/// `-A`'s encoding: A's coordinates, each checked canonical, with `y` negated modulo `p`. Whether the point is on the
/// curve is checked when it is decoded for the pairing, as the reference does.
fn decode_coordinates(a: &[u8]) -> Result<[u8; G1_BYTES], Groth16Error> {
    let (x, y) = a.split_at(WORD_BYTES);
    let ax = bn::Fq::from_slice(x).map_err(|_| malformed("A.x is not a canonical field element"))?;
    let ay = bn::Fq::from_slice(y).map_err(|_| malformed("A.y is not a canonical field element"))?;
    Ok(encode_coordinates(ax, -ay))
}

/// `x || y`, whether or not the point is on the curve.
fn encode_coordinates(x: bn::Fq, y: bn::Fq) -> [u8; G1_BYTES] {
    let mut out = [0u8; G1_BYTES];
    for (o, b) in out.iter_mut().zip(super::to_word(x).into_iter().chain(super::to_word(y))) {
        *o = b;
    }
    out
}

